// ─── Helper: translate an ISAA label ───
export function translateIsaaLabel(label: string, lang: AppLanguage): string {
  return ISAA_LABELS_I18N[lang]?.[label] || ISAA_LABELS_I18N.English[label] || label;
}

// ─── Helper: join items as a sentence ───
export function joinItems(items: string[], lang: AppLanguage): string {
  const list = items.slice(0, 3);
  if (list.length === 0) return '';
  if (lang === 'Hindi') {
    if (list.length === 1) return list[0];
    if (list.length === 2) return `${list[0]} અને ${list[1]}`.replace('અને', 'ઔર');
    return `${list.slice(0, -1).join(', ')}, ઔર ${list[list.length - 1]}`.replace('ઔર', 'ઔર');
  }
  if (lang === 'Gujarati') {
    if (list.length === 1) return list[0];
    if (list.length === 2) return `${list[0]} અને ${list[1]}`;
    return `${list.slice(0, -1).join(', ')}, અને ${list[list.length - 1]}`;
  }
  // Default English-style for Kannada, Tamil
  if (list.length === 1) return list[0];
  if (list.length === 2) return `${list[0]} and ${list[1]}`;
  return `${list.slice(0, -1).join(', ')}, and ${list[list.length - 1]}`;
}
